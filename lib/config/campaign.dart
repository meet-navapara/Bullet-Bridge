class ChapterDef {
  const ChapterDef({
    required this.number,
    required this.name,
    required this.tagline,
    required this.theme,
    required this.signature,
    required this.introductions,
  });

  final int number;
  final String name;
  final String tagline;
  final ArenaTheme theme;

  /// Wave pattern this chapter leans on.
  final SpawnPattern signature;

  /// Slot (1-10) → mechanic first introduced there.
  final Map<int, Mechanic> introductions;

  BossDef get boss => Bosses.forChapter(number);
  int get firstLevel => (number - 1) * StageSpec.levelsPerChapter + 1;
  int get lastLevel => number * StageSpec.levelsPerChapter;
}

/// Intensity template for one slot of a chapter.
class SlotDef {
  const SlotDef({
    required this.category,
    required this.waves,
    required this.hpFactor,
    required this.paceOffset,
    required this.extraBalls,
    required this.patterns,
    this.hazards = 1,
  });

  final LevelCategory category;
  final int waves;
  final double hpFactor;
  final double paceOffset;

  /// Added to the chapter's base ball count per wave.
  final int extraBalls;

  /// Wave patterns: `null` entries mean "the chapter signature", and
  /// [SpawnPattern.mixed] in a slot that introduces a mechanic is replaced
  /// by that mechanic's pattern.
  final List<SpawnPattern?> patterns;
  final int hazards;
}

/// One fully resolved campaign level.
class LevelDef {
  const LevelDef({
    required this.number,
    required this.category,
    required this.waves,
    required this.patterns,
    required this.ballsPerWave,
    required this.maxTier,
    required this.durability,
    required this.pace,
    required this.drift,
    required this.bounce,
    required this.mechanics,
    required this.hazardsPerWave,
    required this.clearBonus,
    required this.coinScale,
    this.introduces,
    this.boss,
  });

  final int number;
  final LevelCategory category;
  final int waves;

  /// Pattern for each wave (index 0 = wave 1). Boss levels list only the
  /// warm-up waves; the boss wave follows them.
  final List<SpawnPattern> patterns;
  final int ballsPerWave;
  final int maxTier;

  /// Durability scale of wave 1 (hit points per tier factor).
  final double durability;
  final double pace;
  final double drift;
  final BounceProfile bounce;

  /// Everything unlocked so far (enemy types, hazards, affinities).
  final Set<Mechanic> mechanics;
  final int hazardsPerWave;
  final int clearBonus;
  final double coinScale;
  final Mechanic? introduces;
  final BossDef? boss;

  int get chapter => StageSpec.chapterOf(number);
  int get slot => (number - 1) % StageSpec.levelsPerChapter + 1;
  bool get isBoss => boss != null;
  ChapterDef get chapterDef => Campaign.chapters[chapter - 1];

  bool has(Mechanic m) => mechanics.contains(m);

  /// This level's animated sky.
  LevelAnimation get animation => LevelAnimation.forLevel(number);

  /// What the level asks of the player. Durability and pace are left out on
  /// purpose: two levels differing only in those numbers play the same.
  String get combination =>
      '${patterns.map((p) => p.name).join(',')}|$ballsPerWave|$maxTier|'
      '${bounce.name}|$hazardsPerWave|${mechanics.length}|${boss?.name}';

  /// Affinities enemies may carry in this level.
  List<Element> get affinities => [
    if (has(Mechanic.emberAffinity)) Element.fire,
    if (has(Mechanic.fullAffinity)) ...[Element.ice, Element.electric],
  ];

  /// Hazard kinds available in this level.
  List<HazardKind> get hazardKinds => [
    if (has(Mechanic.blaze)) HazardKind.blaze,
    if (has(Mechanic.frost)) HazardKind.frost,
    if (has(Mechanic.storm)) HazardKind.storm,
  ];

  /// Title-card hint.
  String get hint {
    final b = boss;
    if (b != null) return 'BOSS: ${b.tip}';
    final m = introduces;
    if (m != null) return m.intro;
    return switch (category) {
      LevelCategory.intro ||
      LevelCategory.recovery => 'A breather. Collect coins and power up!',
      LevelCategory.easy => 'Warm up. Big crystals split into smaller ones.',
      LevelCategory.normal => 'Keep moving and keep firing.',
      LevelCategory.newPattern => 'A new pattern. Watch before you commit.',
      LevelCategory.challenge => 'Short and sharp. Stay focused!',
      LevelCategory.hard => 'Tougher crystals. Use your elements.',
      LevelCategory.preparation => 'A long fight. Save power-ups for later.',
      LevelCategory.finalTest => 'Final test before ${chapterDef.boss.name}!',
      LevelCategory.boss => '',
    };
  }
}

/// Field replacements for one level (see [Campaign.overrides]).
class LevelOverride {
  const LevelOverride({
    this.waves,
    this.patterns,
    this.ballsPerWave,
    this.maxTier,
    this.hpFactor,
    this.paceOffset,
    this.bounce,
    this.hazardsPerWave,
  });

  final int? waves;
  final List<SpawnPattern>? patterns;
  final int? ballsPerWave;
  final int? maxTier;
  final double? hpFactor;
  final double? paceOffset;
  final BounceProfile? bounce;
  final int? hazardsPerWave;
}

