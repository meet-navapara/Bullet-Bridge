  static List<LevelDef> _buildLevels() {
    final used = <String>{};
    return [
      for (var n = 1; n <= StageSpec.levelCount; n++)
        n <= StageSpec.authoredLevels
            ? _remember(_build(n), used)
            : _buildUnique(n, used),
    ];
  }

  static LevelDef _remember(LevelDef level, Set<String> used) {
    used.add(level.combination);
    return level;
  }

  /// Tries seeded remixes of a generated level until one is new.
  static LevelDef _buildUnique(int n, Set<String> used) {
    const maxAttempts = 500;
    for (var attempt = 0; attempt < maxAttempts; attempt++) {
      final level = _build(n, _remix(n, attempt));
      if (used.add(level.combination)) return level;
    }
    throw StateError('No unique combination left for level $n');
  }

