/// The 1000-level campaign as data.
///
/// Levels are built from three small tables instead of 1000 hand-written
/// files:
/// - [Campaign.chapters]: theme, signature wave pattern and the mechanics a
///   chapter introduces;
/// - [Campaign.slots]: the intensity template for the ten levels of every
///   chapter (easy → new mechanic → challenge → recovery → … → boss);
/// - the curves in [CampaignSpec] / [SpeedSpec] (durability, pace, drift).
///
/// [Campaign.overrides] can replace any field of any level. Chapters 1-10 are
/// written by hand. Later chapters reuse their worlds in new colours, and
/// their levels are remixed from a fixed seed, so every player gets the same
/// campaign and no two levels share a [LevelDef.combination]. Every level is
/// validated by test/config/campaign_test.dart and summarised in
/// docs/LEVEL_BALANCING.md (generated by tool/balance/campaign_report_test).
