enum LevelCategory {
  intro,
  easy,
  normal,
  newPattern,
  challenge,
  recovery,
  hard,
  preparation,
  finalTest,
  boss,
}

/// How one wave's enemies are composed.
enum SpawnPattern {
  /// Mixed sizes, biggest first (the classic wave).
  standard,

  /// Many small crystals.
  swarm,

  /// One or two huge, slow, durable crystals.
  giants,

  /// Mostly rock-shelled geodes.
  armored,

  /// Several small geodes.
  armoredSwarm,

  /// Skyrays gliding overhead plus a few crystals.
  skyraid,

  /// A tight cluster of volatile hazards built for chain reactions.
  hazardField,

  /// Gold treasure crystals that fly past once, plus easy crystals.
  treasure,

  /// Crystals with elemental affinities (resist one element, weak to another).
  elemental,

  /// A bit of everything the level allows.
  mixed,
}

enum BounceProfile { normal, low, high }

